// Package platform implements application-owned driver declarations and tooling.
// It never initializes drivers or changes application Wire graphs.
package platform

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"gitlab.com/skyrix-lib/framework/config"
	"go.yaml.in/yaml/v3"
	"golang.org/x/tools/go/packages"
)

const prefix = "//skyrix:platform "
const header = "// Code generated by platformgen. DO NOT EDIT.\n\npackage providers\n"

type Manifest struct {
	Name          string `yaml:"name"`
	ConfigKey     string `yaml:"config_key"`
	ConfigExample string `yaml:"config_example"`
}

// ReadManifest accepts only the three tooling fields; examples describe the
// section body. Neither examples nor manifests are loaded by the application.
func ReadManifest(r io.Reader) (Manifest, error) {
	var m Manifest
	d := yaml.NewDecoder(r)
	d.KnownFields(true)
	if err := d.Decode(&m); err != nil {
		return m, fmt.Errorf("manifest: %w", err)
	}
	var extra any
	if err := d.Decode(&extra); err != io.EOF {
		return m, fmt.Errorf("manifest: expected one document")
	}
	if !regexp.MustCompile(`^[a-z][a-z0-9_-]*$`).MatchString(m.Name) {
		return m, fmt.Errorf("manifest: invalid name %q", m.Name)
	}
	if _, err := config.New(config.Section{Key: m.ConfigKey, Value: &struct{}{}}); err != nil {
		return m, fmt.Errorf("manifest: %w", err)
	}

	var example yaml.Node
	examples := yaml.NewDecoder(strings.NewReader(m.ConfigExample))
	if err := examples.Decode(&example); err != nil {
		return m, fmt.Errorf("manifest: invalid config_example: %w", err)
	}
	if err := examples.Decode(&extra); err != io.EOF {
		return m, fmt.Errorf("manifest: config_example must have one document")
	}
	if len(example.Content) != 1 || example.Content[0].Kind != yaml.MappingNode {
		return m, fmt.Errorf("manifest: config_example must be a YAML mapping")
	}
	var mapping map[string]any
	if err := example.Decode(&mapping); err != nil {
		return m, fmt.Errorf("manifest: invalid config_example: %w", err)
	}

	return m, nil
}

type Driver struct {
	ImportPath string
	alias      string
	Manifest   Manifest
}

var importPattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._~/-]*$`)

func validImport(s string) bool {
	return importPattern.MatchString(s) && !strings.Contains(s, "//") && filepath.ToSlash(filepath.Clean(s)) == s && s != "." && s != ".." && !strings.HasPrefix(s, "../")
}

func parse(source []byte) ([]Driver, error) {
	var result []Driver
	seen := map[string]bool{}
	for i, line := range strings.Split(string(source), "\n") {
		text := strings.TrimSpace(line)
		if !strings.HasPrefix(text, strings.TrimSpace(prefix)) {
			continue
		}
		fields := strings.Fields(strings.TrimPrefix(text, strings.TrimSpace(prefix)))
		if len(fields) != 1 || !validImport(fields[0]) {
			return nil, fmt.Errorf("platform.go:%d: expected %s<import-path> (no options)", i+1, prefix)
		}
		if seen[fields[0]] {
			return nil, fmt.Errorf("duplicate driver %q", fields[0])
		}
		seen[fields[0]] = true
		result = append(result, Driver{ImportPath: fields[0]})
	}
	return result, nil
}

// resolve reads explicitly declared packages and their manifest.yaml. It does
// not execute package code, fetch dependencies or install tools.
func resolve(dir string, drivers []Driver) error {
	if len(drivers) == 0 {
		return nil
	}
	patterns := make([]string, len(drivers))
	for i, d := range drivers {
		patterns[i] = d.ImportPath
	}
	loaded, err := packages.Load(&packages.Config{Dir: dir, Mode: packages.NeedName | packages.NeedTypes | packages.NeedFiles, Env: append(os.Environ(), "GOFLAGS=-mod=readonly", "GOPROXY=off", "GOSUMDB=off")}, patterns...)
	if err != nil {
		return err
	}
	byPath := map[string]*packages.Package{}
	for _, p := range loaded {
		byPath[p.PkgPath] = p
	}
	aliases := map[string]bool{"wire": true, "config": true, "sections": true}
	names, keys := map[string]bool{}, map[string]bool{}
	for i := range drivers {
		d := &drivers[i]
		p := byPath[d.ImportPath]
		if p == nil || len(p.Errors) > 0 || p.Types == nil || len(p.GoFiles) == 0 {
			return fmt.Errorf("driver %s is unavailable or invalid; add its dependency explicitly with go get <module>@<version> and retry", d.ImportPath)
		}
		for _, symbol := range []string{"ProviderSet", "Module", "Config", "NewConfig"} {
			if p.Types.Scope().Lookup(symbol) == nil {
				return fmt.Errorf("driver %s must export %s", d.ImportPath, symbol)
			}
		}
		configType, isType := p.Types.Scope().Lookup("Config").(*types.TypeName)
		if !isType {
			return fmt.Errorf("driver %s Config must be a type", d.ImportPath)
		}
		if _, ok := p.Types.Scope().Lookup("Module").(*types.TypeName); !ok {
			return fmt.Errorf("driver %s Module must be a type", d.ImportPath)
		}
		provider, ok := p.Types.Scope().Lookup("ProviderSet").(*types.Var)
		if !ok {
			return fmt.Errorf("driver %s ProviderSet must be a Wire set", d.ImportPath)
		}
		named, ok := provider.Type().(*types.Named)
		if !ok || named.Obj().Pkg() == nil || named.Obj().Pkg().Path() != "github.com/goforj/wire" || named.Obj().Name() != "ProviderSet" {
			return fmt.Errorf("driver %s ProviderSet must use github.com/goforj/wire", d.ImportPath)
		}
		cfg, ok := configType.Type().Underlying().(*types.Struct)
		if !ok || cfg == nil {
			return fmt.Errorf("driver %s Config must be a struct", d.ImportPath)
		}
		sig, ok := p.Types.Scope().Lookup("NewConfig").Type().(*types.Signature)
		if !ok || sig.Params().Len() != 0 || sig.TypeParams().Len() != 0 || sig.Variadic() || sig.Results().Len() != 1 || !types.Identical(sig.Results().At(0).Type(), types.NewPointer(p.Types.Scope().Lookup("Config").Type())) {
			return fmt.Errorf("driver %s requires NewConfig() *Config", d.ImportPath)
		}
		f, err := os.Open(filepath.Join(filepath.Dir(p.GoFiles[0]), "manifest.yaml"))
		if err != nil {
			return fmt.Errorf("driver %s: %w", d.ImportPath, err)
		}
		m, err := ReadManifest(f)
		f.Close()
		if err != nil {
			return fmt.Errorf("driver %s: %w", d.ImportPath, err)
		}
		if names[m.Name] {
			return fmt.Errorf("duplicate driver name %q", m.Name)
		}
		names[m.Name] = true
		normalized := strings.ReplaceAll(m.ConfigKey, ".", "_")
		if keys[normalized] {
			return fmt.Errorf("duplicate config key or env prefix %q", m.ConfigKey)
		}
		keys[normalized] = true
		for _, prev := range drivers[:i] {
			if strings.HasPrefix(m.ConfigKey, prev.Manifest.ConfigKey+".") || strings.HasPrefix(prev.Manifest.ConfigKey, m.ConfigKey+".") {
				return fmt.Errorf("overlapping config keys")
			}
		}
		d.Manifest = m
		parts := strings.Split(d.ImportPath, "/")
		base := p.Name
		if len(parts) > 1 {
			base = parts[len(parts)-2] + base
		}
		base = regexp.MustCompile(`[^A-Za-z0-9_]`).ReplaceAllString(base, "")
		if base == "" || base[0] >= '0' && base[0] <= '9' {
			base = "driver" + base
		}
		alias := base
		for suffix := 2; aliases[strings.ToLower(alias)]; suffix++ {
			alias = fmt.Sprintf("%s%d", base, suffix)
		}
		d.alias = alias
		aliases[strings.ToLower(alias)] = true
	}
	return nil
}

func render(drivers []Driver, configImport string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("\nimport (\nsections \"gitlab.com/skyrix-lib/framework/config\"\n")
	if len(drivers) > 0 {
		fmt.Fprintf(&b, "\"github.com/goforj/wire\"\nconfig %q\n", configImport)
		for _, d := range drivers {
			fmt.Fprintf(&b, "%s %q\n", d.alias, d.ImportPath)
		}
	}
	b.WriteString(")\n")
	for _, d := range drivers {
		name := strings.ToUpper(d.alias[:1]) + d.alias[1:]
		if strings.HasPrefix(name, "_") {
			name = "Driver" + name
		}
		fmt.Fprintf(&b, "\nvar %sSet = wire.NewSet(%s.ProviderSet, Provide%sConfig)\n", name, d.alias, name)
		fmt.Fprintf(&b, "func Provide%sConfig(cfg *config.Config) (*%s.Config,error) {\nvalue := %s.NewConfig()\nerr := cfg.LoadSections(sections.Section{Key:%q,Value:value})\nreturn value,err\n}\n", name, d.alias, d.alias, d.Manifest.ConfigKey)
	}
	b.WriteString("\n// PlatformSections supplies fresh defaults for config:env; it loads nothing.\nfunc PlatformSections() []sections.Section { return []sections.Section{\n")
	for _, d := range drivers {
		fmt.Fprintf(&b, "{Key:%q,Value:%s.NewConfig()},\n", d.Manifest.ConfigKey, d.alias)
	}
	b.WriteString("} }\n")
	return format.Source(b.Bytes())
}
