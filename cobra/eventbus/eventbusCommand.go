package eventbus

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"runtime/debug"
	"strings"

	support "gitlab.com/skyrix-lib/framework/scaffold"

	"github.com/spf13/cobra"
)

const eventBusGeneratedHeader = "// Code generated by skyrix eventbus command. DO NOT EDIT."

var eventBusPackages = []string{"events", "consumers", "publishers", "subscribers"}

// EventBusCommand manages EventBus transport scaffolding.
type EventBusCommand struct {
	ProjectRoot string
	ModulePath  string
}

func NewEventBusCommand() *EventBusCommand {
	return &EventBusCommand{ProjectRoot: ".", ModulePath: buildModulePath()}
}

func (c *EventBusCommand) ToCobraCommand() *cobra.Command {
	command := &cobra.Command{
		Use:     "eventbus",
		Aliases: []string{"bus"},
		Short:   "Create and manage EventBus transport components",
		Long: `Create EventBus transport components in role-based packages:
  internal/transport/eventbus/events
  internal/transport/eventbus/consumers
  internal/transport/eventbus/publishers
  internal/transport/eventbus/subscribers

Install the Go library separately:
  go get gitlab.com/skyrix-lib/eventbus@v1.0.0

After init, create an event contract first. For an incoming event add a
consumer and subscriber. For an outgoing event add a publisher. Catalog and
Delivery belong in subjects and event names; they are not transport packages.
No Saga or application-layer code is generated.`,
		Example: strings.Join([]string{
			"  ./cobra eventbus init",
			"  ./cobra eventbus event create CatalogPaymentHoldRequested --subject catalog.payment_hold.requested.v1",
			"  ./cobra eventbus consumer create CatalogPaymentHoldRequested",
			"  ./cobra eventbus subscriber create CatalogPaymentHoldRequested",
			"  ./cobra eventbus event create PaymentCatalogHoldSucceeded --subject payment.catalog_hold.succeeded.v1",
			"  ./cobra eventbus publisher create PaymentCatalogHoldSucceeded",
			"  ./cobra eventbus list",
		}, "\n"),
	}

	command.AddCommand(
		c.newInitCommand(),
		c.newListCommand(),
		c.newRemoveCommand(),
		c.newEventCommand(),
		c.newConsumerCommand(),
		c.newPublisherCommand(),
		c.newSubscriberCommand(),
	)
	return command
}

func (c *EventBusCommand) newInitCommand() *cobra.Command {
	return &cobra.Command{
		Use:   "init",
		Short: "Initialize role-based EventBus transport packages",
		Long: `Create events, consumers, publishers, and subscribers packages with
their Wire providers. Component create commands also initialize this structure
automatically, so running init explicitly is optional.`,
		Example: `  ./cobra eventbus init`,
		Args:    cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			root, err := support.DirectoryRoot(c.ProjectRoot)
			if err != nil {
				return err
			}
			initialized, err := c.ensureInitialized(root)
			if err != nil {
				return err
			}
			if !initialized {
				return fmt.Errorf("eventbus transport is already initialized: %s", eventBusTransportRoot(root))
			}
			fmt.Fprintf(cmd.OutOrStdout(), "eventbus initialized: %s\n", eventBusTransportRoot(root))
			fmt.Fprintln(cmd.OutOrStdout(), "next incoming: eventbus event create <Event> --subject <subject>; then consumer create <Event>; then subscriber create <Event>")
			fmt.Fprintln(cmd.OutOrStdout(), "next outgoing: eventbus event create <Event> --subject <subject>; then publisher create <Event>")
			return nil
		},
	}
}

func (c *EventBusCommand) ensureInitialized(root string) (bool, error) {
	transportRoot := eventBusTransportRoot(root)
	if info, err := os.Stat(transportRoot); err == nil {
		if !info.IsDir() {
			return false, fmt.Errorf("eventbus transport path is not a directory: %s", transportRoot)
		}
		for _, packageName := range eventBusPackages {
			if err := c.ensurePackage(root, packageName); err != nil {
				return false, err
			}
		}
		if err := c.writeRootProvider(root); err != nil {
			return false, err
		}
		return false, nil
	} else if !os.IsNotExist(err) {
		return false, fmt.Errorf("inspect eventbus transport: %w", err)
	}

	for _, packageName := range eventBusPackages {
		if err := c.ensurePackage(root, packageName); err != nil {
			return false, err
		}
	}
	if err := c.writeRootProvider(root); err != nil {
		return false, err
	}
	return true, nil
}

func (c *EventBusCommand) ensurePackage(root, packageName string) error {
	dir := filepath.Join(eventBusTransportRoot(root), packageName)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("create eventbus %s package: %w", packageName, err)
	}
	if packageName == "events" {
		envelope := filepath.Join(dir, "envelope.go")
		if _, err := os.Stat(envelope); err == nil {
			return nil
		} else if !os.IsNotExist(err) {
			return fmt.Errorf("inspect events envelope: %w", err)
		}
		content := fmt.Sprintf(`%s

package events

import "time"

// Envelope is the shared JSON metadata shape for EventBus messages.
type Envelope[T any] struct {
	EventID        string    `+"`json:\"event_id\"`"+`
	EventType      string    `+"`json:\"event_type\"`"+`
	EventVersion   int       `+"`json:\"event_version\"`"+`
	OccurredAt     time.Time `+"`json:\"occurred_at\"`"+`
	Producer       string    `+"`json:\"producer\"`"+`
	TraceID        string    `+"`json:\"trace_id,omitempty\"`"+`
	IdempotencyKey string    `+"`json:\"idempotency_key\"`"+`
	Payload        T         `+"`json:\"payload\"`"+`
}
`, eventBusGeneratedHeader)
		return support.WriteNewFile(envelope, []byte(content))
	}
	provider := filepath.Join(dir, "provider.go")
	if _, err := os.Stat(provider); err == nil {
		return nil
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("inspect %s provider: %w", packageName, err)
	}
	content := fmt.Sprintf(`%s

package %s

import "github.com/google/wire"

// ProviderSet contains generated %s providers.
var ProviderSet = wire.NewSet()
`, eventBusGeneratedHeader, packageName, packageName)
	return support.WriteNewFile(provider, []byte(content))
}

func (c *EventBusCommand) writeRootProvider(root string) error {
	module, err := c.modulePath(root)
	if err != nil {
		return err
	}
	content := fmt.Sprintf(`%s

package eventbus

import (
	"github.com/google/wire"

	"%s/internal/transport/eventbus/consumers"
	"%s/internal/transport/eventbus/publishers"
	"%s/internal/transport/eventbus/subscribers"
)

// ProviderSet contains all generated EventBus transport providers.
var ProviderSet = wire.NewSet(
	consumers.ProviderSet,
	publishers.ProviderSet,
	subscribers.ProviderSet,
)
`, eventBusGeneratedHeader, module, module, module)
	formatted, err := format.Source([]byte(content))
	if err != nil {
		return fmt.Errorf("format eventbus provider: %w", err)
	}
	path := filepath.Join(eventBusTransportRoot(root), "provider.go")
	if existing, err := os.ReadFile(path); err == nil {
		if !strings.HasPrefix(string(existing), eventBusGeneratedHeader) {
			// The application may own a richer provider. Initialization must not overwrite it.
			return nil
		}
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("read eventbus provider: %w", err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		return fmt.Errorf("write eventbus provider: %w", err)
	}
	return nil
}

func eventBusTransportRoot(root string) string {
	return filepath.Join(root, "internal", "transport", "eventbus")
}

func (c *EventBusCommand) modulePath(root string) (string, error) {
	if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
		return support.ModulePath(root)
	} else if !os.IsNotExist(err) {
		return "", fmt.Errorf("inspect go.mod: %w", err)
	}
	if module := strings.TrimSpace(c.ModulePath); module != "" {
		return module, nil
	}
	return buildModulePath(), nil
}

func buildModulePath() string {
	if info, ok := debug.ReadBuildInfo(); ok {
		module := strings.TrimSpace(info.Main.Path)
		if module != "" && module != "command-line-arguments" {
			return module
		}
	}
	return "skyrix"
}
